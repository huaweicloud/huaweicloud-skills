#!/usr/bin/env python3
"""
DCS master-slave failover — execution script.

Reads region and instance_id from config/config.json,
loads the config directory generated by prepare, safely executes master-slave
failover (ChangeMasterStandby), polls for failover completion, runs consistency
checks, and saves the execution result.

Usage:
  # Execute failover (real failover by default)
  python3 execute.py --config-dir <path>

  # Skip critical risk blocking from prepare (requires manual risk confirmation)
  python3 execute.py --config-dir <path> --force
"""

import argparse
import datetime
import os
import sys
import time

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

sys.path.insert(0, SCRIPT_DIR)
from config import load_config, get_config_path, run_hcloud, load_json, save_json
import risk


# ---------------------------------------------------------------------------
# Query instance / nodes
# ---------------------------------------------------------------------------

def get_instance(region, instance_id):
    """Query a single DCS instance detail."""
    resp = run_hcloud("DCS", "ShowInstance", region, [f"--instance_id={instance_id}"])
    if resp.get("_error"):
        return None, resp.get("stderr")
    return resp, None


def get_nodes(region, instance_id):
    """Query master-slave node info."""
    resp = run_hcloud("DCS", "ShowNodesInformation", region, [f"--instance_id={instance_id}"])
    if resp.get("_error"):
        return None, resp.get("stderr")
    nodes = resp.get("nodes", [])
    master = next((n for n in nodes if (n.get("node_type") or "").lower() in ("master", "primary")), None)
    slave = next((n for n in nodes if (n.get("node_type") or "").lower() in ("slave", "replica", "standby")), None)
    return {"nodes": nodes, "master": master, "slave": slave}, None


def node_info(node):
    if not node:
        return {"name": "N/A", "type": "N/A", "status": "N/A", "az": "N/A", "id": "N/A"}
    return {
        "name": node.get("name", "N/A"),
        "type": node.get("node_type", "N/A"),
        "status": node.get("status", "N/A"),
        "az": node.get("az_code", "N/A"),
        "id": node.get("node_id", "N/A"),
    }


# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Execute failover
# ---------------------------------------------------------------------------

def execute_failover(region, instance_id):
    """Call DCS ChangeMasterStandby API to trigger master-slave failover.

    Returns:
        (resp, err): on success (resp, None); on failure (full resp with _error/timeout flag, stderr).
    """
    resp = run_hcloud("DCS", "ChangeMasterStandby", region, [f"--instance_id={instance_id}"])
    if resp.get("_error"):
        return resp, resp.get("stderr")
    return resp, None


def poll_failover(region, instance_id, old_slave_id, max_wait=120, interval=5):
    """Poll for failover completion, return timeline.

    Completion criteria: master node_id becomes the original slave (old_slave_id)
    and instance status returns to RUNNING.
    """
    timeline = []
    result = "timeout"
    after_master = {}
    after_slave = {}
    start = time.time()

    while True:
        elapsed = int(time.time() - start)
        if elapsed >= max_wait:
            break

        nodes, err = get_nodes(region, instance_id)
        if nodes is None:
            timeline.append({"elapsed": elapsed, "status": "ERROR", "master": "", "slave": ""})
            time.sleep(interval)
            continue

        inst, _ = get_instance(region, instance_id)
        status = inst.get("status") if inst else "N/A"
        master = nodes.get("master")
        slave = nodes.get("slave")
        master_info = node_info(master)
        slave_info = node_info(slave)
        master_id = master.get("node_id") if master else None

        print(f"  [{elapsed}s] status={status}, master={master_info['name']}(az={master_info['az']}), slave={slave_info['name']}(az={slave_info['az']})")
        timeline.append({"elapsed": elapsed, "status": status,
                         "master": master_info["name"], "slave": slave_info["name"],
                         "master_id": master_id, "slave_id": slave.get("node_id") if slave else None,
                         "master_az": master_info["az"], "slave_az": slave_info["az"]})

        # Match by node ID (more stable than name), confirm slave has been promoted to master
        if master_id and old_slave_id and master_id == old_slave_id:
            after_master = master_info
            after_slave = slave_info
            # Slave promoted to master, keep polling until status returns to RUNNING
            while elapsed < max_wait:
                time.sleep(interval)
                elapsed = int(time.time() - start)
                nodes2, _ = get_nodes(region, instance_id)
                inst2, _ = get_instance(region, instance_id)
                if nodes2 is None:
                    break
                status2 = inst2.get("status") if inst2 else "N/A"
                m2 = node_info(nodes2.get("master"))
                s2 = node_info(nodes2.get("slave"))
                print(f"  [{elapsed}s] status={status2}, master={m2['name']}(az={m2['az']}), slave={s2['name']}(az={s2['az']})")
                timeline.append({"elapsed": elapsed, "status": status2,
                                 "master": m2["name"], "slave": s2["name"],
                                 "master_id": nodes2.get("master", {}).get("node_id") if nodes2.get("master") else None,
                                 "slave_id": nodes2.get("slave", {}).get("node_id") if nodes2.get("slave") else None,
                                 "master_az": m2["az"], "slave_az": s2["az"]})
                if status2 == "RUNNING":
                    result = "success"
                    break
            if result != "success":
                result = "timeout"
                print(f"  [警告] 倒换已完成（备节点已提升为主），但实例状态未恢复 RUNNING，超时退出。")
            break

        time.sleep(interval)

    if result == "timeout":
        nodes, _ = get_nodes(region, instance_id)
        if nodes:
            after_master = node_info(nodes.get("master"))
            after_slave = node_info(nodes.get("slave"))

    elapsed = int(time.time() - start)
    return {"timeline": timeline, "after_master": after_master, "after_slave": after_slave,
            "result": result, "duration_seconds": elapsed}


# ---------------------------------------------------------------------------
# Consistency check
# ---------------------------------------------------------------------------

def consistency_check(region, instance_id, before_master_az, before_master_id=None):
    """Post-failover data consistency check.

    DCS is managed Redis with no direct read-only key-count API at the CLI level;
    use the master node topology (ShowInstanceTopology) dbs.keys / used_memory
    to compare data volume before and after failover.

    Master-slave swap detection: use ShowNodesInformation to get the current master's
    az_code and node_id, compare with before_master_az / before_master_id —
    a change in node_id or AZ confirms the swap.
    """
    print("  [一致性] 执行数据一致性检查...")
    checks = []

    # 1. Use ShowNodesInformation to determine if master-slave roles swapped (az + node_id comparison)
    nodes_resp = run_hcloud("DCS", "ShowNodesInformation", region, [f"--instance_id={instance_id}"])
    if nodes_resp.get("_error") or not nodes_resp.get("nodes"):
        checks.append({"name": "节点状态查询", "value": nodes_resp.get("stderr", "查询失败"), "ok": False})
    else:
        nodes_list = nodes_resp["nodes"]
        master_node = next((n for n in nodes_list if (n.get("node_type") or "").lower() in ("master", "primary")), None)
        if not master_node:
            checks.append({"name": "倒换后主节点定位", "value": "未找到主节点", "ok": False})
        else:
            current_master_az = master_node.get("az_code", "")
            current_master_id = master_node.get("node_id", "")
            az_changed = before_master_az and current_master_az and current_master_az != before_master_az
            id_changed = before_master_id and current_master_id and current_master_id != before_master_id
            swapped = bool(az_changed or id_changed)
            checks.append({
                "name": "主节点已切换（AZ或node_id变化）",
                "value": f"before_az={before_master_az} → after_az={current_master_az} | before_id={before_master_id or 'N/A'} → after_id={current_master_id}",
                "ok": swapped,
            })

    # 2. Use ShowInstanceTopology to get key count and memory
    resp = run_hcloud("DCS", "ShowInstanceTopology", region, [f"--instance_id={instance_id}"])
    if resp.get("_error"):
        checks.append({"name": "拓扑数据查询", "value": resp.get("stderr", "查询失败"), "ok": True})
    else:
        servers = resp.get("redis_server", [])
        master = next((s for s in servers if (s.get("node_type") or "").lower() == "master"), None)
        if master:
            keys = master.get("dbs", {}).get("keys") if isinstance(master.get("dbs"), dict) else None
            mem = master.get("used_memory")
            if keys is not None:
                checks.append({"name": "主节点key数量", "value": keys, "ok": True})
            else:
                checks.append({"name": "主节点key数量", "value": "不可用", "ok": True})
            if mem is not None:
                checks.append({"name": "主节点内存(MB)", "value": mem, "ok": True})
        else:
            checks.append({"name": "拓扑主节点定位", "value": "未找到主节点", "ok": True})

    total = len(checks)
    ok = sum(1 for c in checks if c["ok"])
    return {"checks": checks, "total": total, "ok_count": ok,
            "verdict": "ok" if ok == total else ("warn" if ok else "err")}


# ---------------------------------------------------------------------------
# Main flow
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="DCS 主备倒换执行")
    parser.add_argument("--config-dir", required=True, help="prepare 生成的配置目录")
    parser.add_argument("--force", action="store_true", help="跳过 prepare 阶段检测出的严重风险拦截（需人工确认）")
    args = parser.parse_args()

    config_dir = args.config_dir
    if not os.path.isdir(config_dir):
        print(f"[ERROR] 配置目录不存在: {config_dir}")
        sys.exit(1)

    config_path = get_config_path()
    print(f"[配置] 读取共享配置: {config_path}")
    try:
        cfg = load_config()
    except (FileNotFoundError, ValueError) as e:
        print(f"[ERROR] {e}")
        sys.exit(1)

    region = cfg["region"]
    instance_id = cfg["instance_id"]

    experiment = load_json(os.path.join(config_dir, "experiment.json"))
    iam_policy = load_json(os.path.join(config_dir, "iam_policy.json"))

    # Prefer target.instance_id from experiment.json if present
    exp_instance_id = experiment.get("target", {}).get("instance_id")
    if exp_instance_id and exp_instance_id != instance_id:
        instance_id = exp_instance_id
        print(f"[配置] instance_id 已从 experiment.json 覆盖为 {instance_id}")

    instance_name = experiment["target"].get("instance_name", instance_id)
    safety = experiment.get("safety_checks", {})
    max_wait = safety.get("max_failover_duration_seconds", 120)
    interval = safety.get("poll_interval_seconds", 5)

    print(f"[配置] 实验名称: {experiment.get('experiment_name', 'N/A')}")
    print(f"[配置] region={region} | instance_id={instance_id} | 目标实例: {instance_name}")

    # -- Pre-check --
    print(f"\n[预检查] 查询实例状态...")
    inst, err = get_instance(region, instance_id)
    if err:
        print(f"[ERROR] {err}")
        sys.exit(1)
    status = inst.get("status")
    cache_mode = inst.get("cache_mode")
    nodes, err = get_nodes(region, instance_id)
    if err:
        print(f"[ERROR] 查询节点信息失败: {err}")
        sys.exit(1)
    master = nodes.get("master")
    slave = nodes.get("slave")
    before_master = node_info(master)
    before_slave = node_info(slave)

    if not master or not slave:
        print(f"[ERROR] 实例缺少主/备节点（master={'有' if master else '无'}, slave={'有' if slave else '无'}）。")
        print(f"  无法执行倒换。请确认实例为主备类型且节点信息完整。")
        sys.exit(1)
    if before_slave.get("id", "N/A") == "N/A" or before_master.get("id", "N/A") == "N/A":
        print(f"[ERROR] 主/备节点缺少 node_id 字段（master_id={before_master.get('id')}, slave_id={before_slave.get('id')}）。")
        sys.exit(1)

    print(f"  实例: {instance_name} | 状态: {status} | cache_mode: {cache_mode}")
    print(f"  主节点: {before_master['name']} (AZ={before_master['az']})")
    print(f"  备节点: {before_slave['name']} (AZ={before_slave['az']})")

    # -- Safety checks --
    checks = {"instance_found": True, "status_running": status == "RUNNING",
              "is_ha": cache_mode == "ha"}
    if safety.get("require_ha_type") and not checks["is_ha"]:
        print(f"[ERROR] 实例非主备类型（cache_mode={cache_mode}），无法倒换。")
        sys.exit(1)
    if safety.get("require_running_status") and not checks["status_running"]:
        print(f"[ERROR] 实例状态为 {status}，非 RUNNING，无法倒换。")
        sys.exit(1)

    iam_check = iam_policy.get("iam_check_result", {})
    checks["iam_dcs_access"] = iam_check.get("dcs_read_access", False)
    checks["iam_failover_capable"] = iam_check.get("dcs_failover_capable", False)

    iam_status = iam_check.get("dcs_failover_status", "unknown")
    if iam_status == "deny":
        print(f"\n[安全拦截] 确认无倒换权限（status=deny），阻止执行。")
        if not args.force:
            print(f"[ERROR] 已阻止执行。请确认 IAM 权限后重新运行 prepare，或经人工确认放行后重试。")
            sys.exit(1)
        else:
            print(f"[警告] 已跳过 IAM 权限拦截（经人工确认放行），请确认倒换权限无误。")
    elif iam_status == "unknown":
        print(f"\n[安全提示] 倒换权限未知（status=unknown，系统策略无法取证）。此为建议性检查，不阻断执行。")

    print(f"  安全检查: {'全部通过' if all(checks.values()) else '部分未通过'}")
    for k, v in checks.items():
        print(f"    {k}: {'✓' if v else '✗'}")

    print(f"\n  倒换后，备节点 {before_slave['name']} (AZ={before_slave['az']}) 将被提升为主节点。")

    # -- Risk warning and blocking (read risk_assessment.json from prepare) --
    risk_path = os.path.join(config_dir, "risk_assessment.json")
    risk_blocked = False
    if os.path.isfile(risk_path):
        risk_doc = load_json(risk_path)
        risk_inst = risk_doc.get("instance_id")
        risk_region = risk_doc.get("region")
        risk_mismatch = (risk_inst and risk_inst != instance_id) or (risk_region and risk_region != region)
        if risk_mismatch:
            print(f"\n[风险拦截] risk_assessment.json 与当前待倒换实例不一致！")
            print(f"  风险评估对象: instance={risk_inst} region={risk_region}")
            print(f"  当前待倒换实例: {instance_id} region={region}")
            if not args.force:
                print(f"[ERROR] 已阻止执行。请先运行 prepare 生成当前实例的风险评估，或确认实例无误并经人工确认放行后重试。")
                sys.exit(1)
            else:
                print(f"[警告] 已对不一致的风险评估强制演练（经人工确认放行），请人工复核实例与风险。")
        else:
            rlvl = risk_doc.get("overall_level", "low")
            print(f"\n[风险提示] 总体风险等级: {rlvl}（来源: risk_assessment.json，与当前实例一致）")
            for it in risk_doc.get("items", []):
                if it.get("level") in ("critical", "warning", "unknown"):
                    mark = {"critical": "🔴", "warning": "🟠", "unknown": "⚪"}.get(it.get("level"), "•")
                    print(f"  {mark} [{it.get('category')}] {it.get('title')} — {it.get('detail')}")
            risk_blocked = risk_doc.get("block_execution", False)
            if risk_blocked:
                print(f"\n[风险拦截] prepare 阶段检测到严重风险项，默认阻止倒换。")
                if not args.force:
                    print(f"[ERROR] 已阻止执行。如已人工评估并接受风险，请经人工确认放行后重试。")
                    sys.exit(1)
                else:
                    print(f"[警告] 已跳过严重风险拦截（经人工确认放行），请确认已人工评估风险。")
    else:
        print(f"\n[风险提示] 未找到 risk_assessment.json（未运行 prepare），跳过风险拦截。")

    # -- Real-time recheck before failover --
    print(f"\n[实时复核] 倒换前复核实例状态与主备节点健康...")
    rt = risk.realtime_safety_check(region, instance_id, master.get("group_id"))
    for sig in rt["signals"]:
        mark = {"critical": "🔴", "warning": "🟠", "info": "🟢"}.get(sig.get("level"), "•")
        print(f"  {mark} {sig.get('title')} — {sig.get('detail')}")
        if sig.get("suggestion"):
            print(f"      建议: {sig.get('suggestion')}")
    if rt["blocked"]:
        if not args.force:
            print(f"[ERROR] 实时复核发现严重风险，已阻止倒换。如确需演练请经人工确认放行后重试（不推荐）。")
            sys.exit(1)
        print(f"[警告] 实时复核发现严重风险，已强制演练（经人工确认放行），请人工确认。")

    # -- Execute failover --
    start_time = datetime.datetime.now()
    print(f"\n[执行] 调用 ChangeMasterStandby...")
    failover_resp, failover_err = execute_failover(region, instance_id)
    if failover_err:
        print(f"[ERROR] 倒换命令调用失败: {failover_err}")
        # Detect DCS.4104 (instance in failover/recovery cooldown, temporarily rejects)
        if "DCS.4104" in str(failover_err):
            print(f"\n[提示] 实例当前处于倒换恢复期（冷却期），属于倒换后的正常保护机制。")
            print(f"       建议等待数分钟（通常 5~10 分钟）让实例完成恢复后再重新执行演练。")
            sys.exit(1)
        # Idempotent guard: command may have been accepted by server (e.g. CLI timeout / non-JSON misjudge).
        # Read-only recheck of current master-slave roles — if slave already promoted, failover actually succeeded, never replay.
        is_timeout = bool(isinstance(failover_resp, dict) and failover_resp.get("timeout"))
        print(f"\n[复核] 命令调用失败（{'CLI 超时' if is_timeout else '其他错误'}），只读验证是否已实际倒换（不重放命令）...")
        nodes_cur, err2 = get_nodes(region, instance_id)
        if err2:
            print(f"[ERROR] 复核失败: {err2}")
            sys.exit(1)
        cur_master = nodes_cur.get("master")
        cur_master_id = cur_master.get("node_id") if cur_master else None
        if cur_master_id and before_slave["id"] and cur_master_id == before_slave["id"]:
            print(f"[OK] 复核确认：原备节点 {before_slave['name']} 已提升为主，倒换实际已成功。继续补全后续流程。")
        else:
            if is_timeout:
                print(f"[ERROR] 复核未发现倒换已生效（master 仍为 {before_master['name']}）。")
                print(f"       可能是 hcloud CLI 本地超时（readTimeout 限制），服务端未受理本次请求。")
                print(f"       请稍后重新执行演练（脚本会重试，无需修改 hcloud 环境配置）。")
            else:
                print(f"[ERROR] 复核未发现倒换已生效（master 仍为 {before_master['name']}），命令确实未受理。")
            sys.exit(1)

    # -- Poll for completion --
    print(f"\n[轮询] 等待倒换完成（max_wait={max_wait}s, interval={interval}s）...")
    poll_result = poll_failover(region, instance_id, before_slave["id"], max_wait, interval)

    if poll_result["result"] == "success":
        print(f"\n[成功] 倒换完成! 耗时 {poll_result['duration_seconds']} 秒")
    else:
        print(f"\n[超时] 倒换未在 {max_wait}s 内完成。")

    end_time = datetime.datetime.now()

    # -- Consistency check --
    consistency = consistency_check(region, instance_id, before_master["az"], before_master["id"])

    # -- Save execution result --
    execution_result = {
        "mode": "execute",
        "experiment_name": experiment.get("experiment_name", ""),
        "region": region,
        "instance_id": instance_id,
        "instance_name": instance_name,
        "engine": experiment["target"].get("engine", ""),
        "engine_version": experiment["target"].get("engine_version", ""),
        "capacity": experiment["target"].get("capacity", ""),
        "checks": checks,
        "before_master": before_master,
        "before_slave": before_slave,
        "after_master": poll_result["after_master"],
        "after_slave": poll_result["after_slave"],
        "timeline": poll_result["timeline"],
        "result": poll_result["result"],
        "duration_seconds": poll_result["duration_seconds"],
        "start_time": start_time.strftime("%Y-%m-%d %H:%M:%S"),
        "end_time": end_time.strftime("%Y-%m-%d %H:%M:%S"),
        "consistency_check": consistency,
        "scores": score_result(poll_result, consistency),
    }

    result_path = os.path.join(config_dir, "execution_result.json")
    save_json(result_path, execution_result)
    print(f"\n[完成] 执行结果已保存: {result_path}")
    print(f"\n  下一步: 使用 run.py --phase report 生成报告")
    print(f"  命令: python3 report.py --config-dir {config_dir}")


def score_result(poll_result, consistency):
    """Three-dimensional scoring: failover/data/business.

    failover(40%) + data(30%) + business(30%) -> weighted total.
    """
    # Failover score
    failover_score = 0
    if poll_result["result"] == "success":
        dur = poll_result["duration_seconds"]
        failover_score = 100
        if dur and dur > 30:
            failover_score = max(0, 100 - int((dur - 30) / 10) * 10)
    reasons = []
    if poll_result["result"] != "success":
        reasons.append(f"倒换未完成（{poll_result['result']}）")

    # Data consistency score
    cons = consistency
    total = cons.get("total", 1) or 1
    ok = cons.get("ok_count", 0)
    data_score = int(ok / total * 100)

    # Business score (default 100, deduct if CES connection/latency data abnormal)
    business_score = 100

    total_score = round(failover_score * 0.4 + data_score * 0.3 + business_score * 0.3, 1)
    grade = "优" if total_score >= 85 else ("良" if total_score >= 70 else ("中" if total_score >= 60 else "差"))
    return {
        "failover": {"score": failover_score, "reasons": reasons},
        "data": {"score": data_score},
        "business": {"score": business_score},
        "total": {"score": total_score, "grade": grade,
                  "weights": {"failover": 0.4, "data": 0.3, "business": 0.3}},
    }


if __name__ == "__main__":
    main()
