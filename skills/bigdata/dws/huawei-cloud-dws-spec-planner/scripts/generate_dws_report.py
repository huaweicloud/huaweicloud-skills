# 7. Main entry — generate complete report_data from requirements (single plan)
# =============================================================================

def build_report_data(
    scenario_type: str = "new_build",
    architecture: str = "integrated",
    region: str = "North-Beijing4",
    region_multiplier: float = 1.00,
    data_total_tb: float = 5.0,
    competitor_cores: Optional[int] = None,
    competitor_ratio: Optional[str] = None,
    compute_intensive: bool = False,
    high_point_query: bool = True,
    index_pct: float = 0.30,
    cache_policy: str = "performance",
    hot_data_days: Optional[int] = None,      # v2.3.0 compute-storage separation hot window days: cache only carries most recent N days hot data
    hot_data_gb: Optional[float] = None,      # v2.3.0 compute-storage separation custom hot data total GB (multi-source mixed hot profile)
    daily_increment_gb: Optional[float] = None,
    retention_months: Optional[int] = None,
    project_name: str = "DWS data warehouse planning project",
) -> Dict[str, Any]:
    """
    Auto-complete Phase 3-6 calculations from user requirements, generate complete report_data.

    Notes:
      - CPU / nodes / initial storage all derived from "current/first-batch warehouse data volume data_total_tb" (minimal spec, no over-provisioning);
      - daily_increment_gb (daily GB/day) + retention_months (data retention months) only drive
        storage growth reservation and scale-out cadence recommendations (growth_calc), do not change node config;
      - Cache logic (compute-storage separation, v2.3.0 three modes, by priority):
        hot_data_gb (custom hot data total, mixed data source hot profile) > hot_data_days (hot window N days,
        hot_data=min(daily_increment×N days, full volume)) > cache_policy cost/performance (50%/100%);
        cold data retained long-term in OBS (obs_long_term provides 1/3/5 year growth outlook).
    """
    data_total_gb = data_total_tb * 1024
    custom_mode = bool(
        architecture == "separated" and hot_data_gb and hot_data_gb > 0
    )
    window_mode = bool(
        architecture == "separated" and hot_data_days and daily_increment_gb and daily_increment_gb > 0
    )
    if custom_mode:
        cache_policy = "custom"
    elif window_mode:
        cache_policy = "window"
    # Cache policy display label (cost / performance / window hot window / custom mixed profile)
    if architecture != "separated":
        cache_label = "N/A (full volume local)"
    elif custom_mode:
        _hot_eff = min(hot_data_gb, data_total_gb)
        _ratio = _hot_eff / data_total_gb if data_total_gb > 0 else 0.0
        cache_label = f"Mixed hot profile≈{_hot_eff:.0f}GB ({_ratio:.1%})"
    elif cache_policy == "window":
        cache_label = f"Hot window {hot_data_days} days (daily increment {daily_increment_gb:g}GB×{hot_data_days} days≈{min(daily_increment_gb * hot_data_days, data_total_gb):.0f}GB)"
    elif cache_policy == "cost":
        cache_label = "Cost priority (hot data 50%)"
    else:
        cache_label = "Performance priority (hot data 100%)"

    # 3) CPU (based on current warehouse volume)
    target_vcpu, ratio, cpu_notes = calc_target_vcpu(
        scenario_type, data_total_gb, competitor_cores, competitor_ratio, compute_intensive,
        architecture=architecture,
        cache_policy=cache_policy,
        hot_data_days=hot_data_days,
        daily_increment_gb=daily_increment_gb,
        hot_data_gb_override=hot_data_gb,
    )
    buffer = 0
    base_cores_raw = target_vcpu
    if scenario_type == "new_build" and compute_intensive:
        base = ceil(data_total_gb / 100)
        buffer = target_vcpu - base
        base_cores_raw = base

    cpu_calc = {
        "base_cores": base_cores_raw,
        "buffer_cores": buffer,
        "target_vcpu": target_vcpu,
        "target_ratio": ratio,
        "notes": cpu_notes,
    }

    # 4) Single-plan minimal spec (minimum compute surplus)
    plan = select_min_cost_plan(
        target_vcpu, ratio, architecture, data_total_gb,
        cache_policy, high_point_query, index_pct,
        hot_data_days=hot_data_days, daily_increment_gb=daily_increment_gb,
        hot_data_gb_override=hot_data_gb,
    )

    # 5) Initial storage (based on current warehouse volume & recommended node count)
    storage = calc_storage(
        architecture, data_total_gb, plan["node_count"], cache_policy,
        high_point_query, index_pct,
        hot_data_days=hot_data_days, daily_increment_gb=daily_increment_gb,
        hot_data_gb_override=hot_data_gb,
    )

    # Compute-storage separation OBS (based on current warehouse volume; growth noted in obs_long_term)
    obs = {"obs_gb": 0, "obs_tb": 0, "package_tier_tb": 0, "formula_notes": []}
    obs_long_term = None
    if architecture == "separated":
        obs = calc_obs_storage(data_total_gb)
        # v2.3.0: when daily increment provided (applies to hot window/regular) generate OBS long-term growth outlook
        if daily_increment_gb and daily_increment_gb > 0:
            obs_long_term = calc_obs_long_term_outlook(data_total_gb, daily_increment_gb)

    # 6) Storage capacity filled into plan
    plan["storage_per_node_gb"] = storage["per_node_final_gb"]
    plan["storage_per_node_tb"] = round(storage["per_node_final_gb"] / 1024, 2)
    plan["storage_total_gb"] = storage["per_node_final_gb"] * plan["node_count"]

    # v2.5.0 Selection rationale: generated by computation formula logic chain (①compute→②memory ratio→③concurrency/HA→④storage verification→conclusion)
    reason_text, reason_steps = compose_select_reason(
        scenario_type=scenario_type,
        data_total_gb=data_total_gb,
        target_vcpu=target_vcpu,
        ratio=ratio,
        plan=plan,
        considered=plan["considered"],
        storage=storage,
        high_point_query=high_point_query,
        compute_intensive=compute_intensive,
        competitor_cores=competitor_cores,
    )
    plan["select_reason"] = reason_text
    plan["select_reason_steps"] = reason_steps

    # 7) Growth reservation and scale-out recommendations
    if window_mode or custom_mode:
        # v2.3.0 Cache fixed mode (hot window N days / mixed hot profile custom): local cache disk fixed carrying hot data portion,
        # does not scale with full-volume growth; full-volume increment absorbed long-term elastically by OBS → does not apply "Nth month reaches scale-out line" local disk scale-out model,
        # instead obs_long_term provides OBS package rolling upgrade outlook (growth_calc marks disabled and explains).
        if window_mode:
            _hot_desc = (
                f"Hot window {hot_data_days} days mode: local cache only carries most recent {hot_data_days} days hot data "
                f"(≈{min(daily_increment_gb * hot_data_days, data_total_gb):.0f}GB), capacity fixed, does not scale with full-volume growth"
            )
        else:
            _hot_eff = min(hot_data_gb, data_total_gb)
            _hot_desc = (
                f"Mixed hot data profile mode: local cache fixed carrying hot data ≈{_hot_eff:.0f}GB "
                f"({_hot_eff / data_total_gb:.1%} of full volume), capacity fixed, does not scale with full-volume growth"
            )
        growth = {
            "daily_increment_gb": daily_increment_gb,
            "retention_months": retention_months,
            "enabled": False,
            "window_mode": window_mode,
            "custom_mode": custom_mode,
            "cache_mode": storage["cache_mode"],
            "formula_notes": [
                _hot_desc + "; the criteria for reaching scale-out line is 'daily increment significantly rising' or 'hot window/hot ratio expands', not total data volume growth",
                "Cold data retained long-term in OBS (no fixed retention period): full-volume increment absorbed elastically by OBS on-demand, "
                "OBS package needs rolling upgrade with total capacity growth (1/3/5 year outlook see Sheet5 / report OBS growth section)",
            ],
        }
    else:
        growth = calc_growth(
            data_total_gb=data_total_gb,
            daily_increment_gb=daily_increment_gb,
            retention_months=retention_months,
            high_water=storage["high_water_level"],
            index_pct=index_pct,
            high_point_query=high_point_query,
            cache_ratio=storage["cache_ratio"],
            installed_total_gb=plan["storage_total_gb"],
            architecture=architecture,
            cache_policy=cache_policy,
            obs_total_gb=(plan["storage_total_gb"] if architecture == "separated" else None),
        )

    # Decision rationale (single-plan version)
    req_str = (
        f"Migration scenario competitor {competitor_cores} cores, memory ratio {competitor_ratio}"
        if scenario_type == "migration" else
        f"New-build scenario warehouse {data_total_tb:.1f}TB, {'compute-intensive' if compute_intensive else 'non-compute-intensive'}"
    )
    index_str = f"point query heavy (+{index_pct*100:.0f}% index)" if high_point_query else "report oriented (no extra index)"
    cache_str = f", cache={cache_label}" if architecture == "separated" else ""
    if growth["enabled"]:
        growth_reason = (
            f"Daily increment {growth['daily_increment_gb']:g}GB/day × retention {growth['retention_months']} months "
            f"→ period-end ≈{growth['projected_tb']:g}TB, "
            + ("scale-out needed within retention period" if growth["need_expand"] else "capacity sufficient within retention period")
        )
    elif growth.get("window_mode") or growth.get("custom_mode"):
        growth_reason = (
            "Cache fixed mode (hot window/mixed hot profile): local cache carries fixed hot data without scale-out, "
            "full-volume increment absorbed long-term elastically by OBS (OBS 1/3/5 year package upgrade outlook see report/Excel Sheet5)"
        )
    else:
        growth_reason = "Daily data increment/retention period not provided, no growth prediction"

    decisions = [
        {
            "point": "Architecture mode",
            "candidates": "integrated / separated",
            "selected": architecture,
            "reasoning": (
                "Data volume <20TB, integrated compute-storage architecture is simpler with higher performance (recommended tier)"
                if architecture == "integrated" else
                "Data volume ≥20TB, compute-storage separation elastic scale + lower storage cost (recommended tier)"
                if data_total_tb >= 20 else
                f"User selected compute-storage separation (current {data_total_tb:g}TB<20TB, generally recommend integrated; "
                "chose separated for OBS elasticity and smooth later scale-out, cost-acceptable under cost-priority cache)"
            ),
            "rejected": (
                "Compute-storage separation (extra complexity unnecessary for small datasets)"
                if architecture == "integrated" else
                ("Integrated compute-storage (inconvenient scale-out + high cost for large datasets)" if data_total_tb >= 20 else
                 "Integrated compute-storage (<20TB general recommended tier, can re-evaluate switching if cost sensitive)")
            ),
        },
        {
            "point": "CPU:memory ratio",
            "candidates": "1:4 / 1:8",
            "selected": ratio,
            "reasoning": req_str,
            "rejected": "1:8 (excess memory for non-compute-intensive)" if ratio == "1:4" else "1:4 (insufficient memory for compute-intensive)",
        },
        {
            "point": "Node spec (minimal spec)",
            "candidates": "16/32/64 cores (compute surplus comparison across tiers)",
            "selected": f"{plan['flavor']} ({plan['vcpu']} cores {plan['memory_gb']}GB) × {plan['node_count']} nodes",
            "reasoning": plan["select_reason"],
            "rejected": "Other combos have larger compute surplus or more nodes (see comparison for details)",
        },
        {
            "point": "Storage capacity (initial)",
            "candidates": "Direct capacity allocation / high watermark + index space",
            "selected": (
                f"{architecture}: high watermark {storage['high_water_level']:.0%}, "
                + index_str + cache_str
            ),
            "reasoning": "; ".join(storage["formula_notes"][1:]),
            "rejected": "Direct capacity allocation (insufficient, high watermark usage + index space expansion not considered)",
        },
        {
            "point": "Data growth and scale-out strategy",
            "candidates": "Reserve growth / scale on-demand / compute-storage separation elasticity",
            "selected": ("Growth reservation assessment by daily increment" if growth["enabled"] else "Growth prediction not enabled"),
            "reasoning": growth_reason,
            "rejected": "-",
        },
    ]

    report_data = {
        "project_name": project_name,
        "scenario_type": scenario_type,
        "architecture": architecture,
        "region": region,
        "requirements": {
            "data_total_gb": round(data_total_gb, 0),
            "data_total_tb": data_total_tb,
            "competitor_cores": competitor_cores,
            "competitor_ratio": competitor_ratio,
            "compute_intensive": compute_intensive,
            "high_point_query": high_point_query,
            "index_pct": index_pct,
            "cache_policy": cache_policy if architecture == "separated" else "-",
            "cache_label": cache_label,
            "hot_data_days": hot_data_days if window_mode else None,
            "hot_data_gb": hot_data_gb if custom_mode else None,
            "daily_increment_gb": daily_increment_gb,
            "retention_months": retention_months,
        },
        "cpu_calculation": cpu_calc,
        "plan": plan,                      # Single plan (minimal spec meeting requirements)
        "storage_calc": storage,
        "growth_calc": growth,
        "obs_storage": obs,
        "obs_long_term": obs_long_term,    # v2.3.0 compute-storage separation + daily increment: OBS long-term growth outlook
        "decisions": decisions,
    }
    return report_data


