def calc_obs_storage(data_total_gb: float) -> Dict[str, Any]:
    """OBS capacity calculation for compute-storage separation scenario (based on current warehouse volume)"""
    data_tb = data_total_gb / 1024
    pkg_tb = pick_obs_package(data_tb)
    notes = [
        f"Warehouse data = {data_tb:.1f} TB",
        f"OBS package rounded up → {pkg_tb} TB",
    ]
    return {
        "obs_gb": data_total_gb,
        "obs_tb": round(data_tb, 2),
        "package_tier_tb": pkg_tb,
        "formula_notes": notes,
    }


def calc_obs_long_term_outlook(
    data_total_gb: float,
    daily_increment_gb: float,
) -> Dict[str, Any]:
    """
    v2.3.0 Compute-storage separation + hot window mode OBS long-term growth outlook:
    Cold data retained long-term in OBS (no fixed retention period), local cache disk only carries hot window (fixed capacity, does not scale with total volume),
    so all full-volume growth is absorbed by OBS elastically. Project OBS capacity and package tier at 1/3/5 years
    based on daily increment×30 days/month, for capacity planning reference.
    """
    daily = daily_increment_gb
    milestones = []
    for label, months in (("After 1 year", 12), ("After 3 years", 36), ("After 5 years", 60)):
        growth_gb = daily * GROWTH_DAYS_PER_MONTH * months
        total_gb = data_total_gb + growth_gb
        total_tb = total_gb / 1024
        pkg = pick_obs_package(total_tb)
        milestones.append({
            "label": label,
            "months": months,
            "growth_gb": round(growth_gb, 0),
            "total_gb": round(total_gb, 0),
            "total_tb": round(total_tb, 1),
            "package_tb": pkg,
        })
    return {
        "enabled": True,
        "daily_increment_gb": daily,
        "note": (
            f"Cold data retained long-term in OBS: daily increment {daily:g} GB/day × 30 days/month → monthly increment ≈ {daily*30/1024:.1f} TB; "
            "local cache only carries the most recent N days hot window (fixed capacity, does not scale with full-volume growth); full-volume increment absorbed elastically by OBS on-demand, "
            "OBS package needs rolling upgrade with total capacity growth (see below)"
        ),
        "milestones": milestones,
    }


