def calc_storage(
    architecture: str,      # integrated / separated
    data_total_gb: float,
    nodes: int,
    cache_policy: str = "performance",   # compute-storage separation: cost / performance / window / custom
    high_point_query: bool = True,
    index_pct: float = 0.30,
    hot_data_days: Optional[int] = None,          # compute-storage separation hot window days: cache only carries most recent N days hot data
    daily_increment_gb: Optional[float] = None,   # paired with hot_data_days: hot_data=daily_increment×days
    hot_data_gb_override: Optional[float] = None, # v2.3.0 custom hot data total GB (mixed data source hot profile, given directly)
) -> Dict[str, Any]:
    """
    Calculate per-node storage/cache capacity (based on "current/first-batch warehouse volume", initial config capacity).
    Returns complete calculation process for Sheet 2 use.

    Cache logic (v2.3.0):
      - Compute-storage separation + hot_data_gb_override: hot_data = min(custom hot data volume, full volume)
        —— Mixed multi-source hot profile (e.g. "70G/day source hot 7 days + business existing 50% frequently used" stacked), caller converts total and passes in;
      - Compute-storage separation + hot_data_days: hot_data = min(daily_increment×N days, full volume), cache only carries hot window;
      - Compute-storage separation + cost/performance: hot_data = full volume × 50%/100% (legacy logic);
      - Integrated compute-storage: hot_data = full volume.
    """
    notes_list: List[str] = []
    window_mode = False
    custom_mode = False

    if architecture == "integrated":
        high_water = 0.70
        cache_ratio = 1.0
        hot_data = data_total_gb
    else:  # compute-storage separation
        high_water = 0.80
        if hot_data_gb_override and hot_data_gb_override > 0:
            # v2.3.0 custom hot data volume (mixed data source hot profile)
            custom_mode = True
            hot_data = min(hot_data_gb_override, data_total_gb)
            cache_ratio = hot_data / data_total_gb if data_total_gb > 0 else 0.0
        elif hot_data_days and daily_increment_gb and daily_increment_gb > 0:
            # Hot window mode: cache only most recent N days of incremental hot data
            window_mode = True
            hot_data = min(daily_increment_gb * hot_data_days, data_total_gb)
            cache_ratio = hot_data / data_total_gb if data_total_gb > 0 else 0.0
        elif cache_policy == "cost":
            cache_ratio = 0.5
            hot_data = data_total_gb * cache_ratio
        else:  # performance
            cache_ratio = 1.0
            hot_data = data_total_gb * cache_ratio

    effective = hot_data / high_water
    if high_point_query:
        total_require = effective * (1 + index_pct)
        index_gb = effective * index_pct
    else:
        total_require = effective
        index_gb = 0.0
        index_pct = 0.0

    per_node_require = total_require / nodes
    per_node_final = round_up_to_100(per_node_require)
    total_final = per_node_final * nodes

    # Formula explanation
    if window_mode:
        notes_list.append(
            f"Hot window mode: hot data = daily increment {daily_increment_gb:g}GB/day × {hot_data_days} days = {hot_data:.0f} GB"
            f" ({cache_ratio:.1%} of full volume, only the most recent {hot_data_days} days need high-speed cache, rest goes to OBS)"
        )
    elif custom_mode:
        notes_list.append(
            f"Mixed hot data profile (custom): hot data total = {hot_data_gb_override:g} GB"
            f" → actual cache {hot_data:.0f} GB ({cache_ratio:.1%} of full volume, rest goes to OBS cold storage)"
        )
    else:
        notes_list.append(f"Hot data volume = {data_total_gb:.0f} GB × {cache_ratio:.0%} = {hot_data:.0f} GB")
    notes_list.append(
        f"Effective capacity = {hot_data:.0f} GB / {high_water:.0%}(high watermark) = {effective:.0f} GB"
    )
    if high_point_query:
        notes_list.append(
            f"Includes index space = {effective:.0f} GB × (1+{index_pct:.0%}) = {total_require:.0f} GB"
        )
    else:
        notes_list.append(f"No extra index space, total requirement = {total_require:.0f} GB")
    notes_list.append(
        f"Per-node requirement = {total_require:.0f} GB / {nodes} nodes = {per_node_require:.0f} GB → {per_node_final} GB (rounded up to 100GB)"
    )

    return {
        "arch": architecture,
        "data_total_gb": data_total_gb,
        "high_water_level": high_water,
        "cache_ratio": cache_ratio,
        "cache_mode": ("window" if window_mode else "custom" if custom_mode
                       else ("cost" if architecture == "separated" and cache_policy == "cost" else "performance")),
        "hot_data_days": hot_data_days if window_mode else None,
        "hot_data_gb": hot_data,
        "effective_gb": effective,
        "index_pct": index_pct,
        "index_gb": index_gb,
        "total_require_gb": total_require,
        "nodes": nodes,
        "per_node_require_gb": per_node_require,
        "per_node_final_gb": per_node_final,
        "total_final_gb": total_final,
        "formula_notes": notes_list,
    }


def _est_wrap_lines(text: str, chars_per_line: int = 34) -> int:
    """Estimate total display lines after wrap for multi-line text at given single-line character capacity (for setting Excel row height).

    chars_per_line counted in "character capacity": CJK/full-width ≈ 1 unit, ASCII/half-width ≈ 0.5 unit.
    """
    total = 0
    for seg in str(text).split("\n"):
        units = sum(1.0 if ord(ch) > 127 else 0.5 for ch in seg)
        total += max(1, math.ceil(units / max(chars_per_line, 1)))
    return total


def compose_select_reason(
    scenario_type: str,
    data_total_gb: float,
    target_vcpu: int,
    ratio: str,
    plan: Dict[str, Any],
    considered: List[Dict[str, Any]],
    storage: Dict[str, Any],
    high_point_query: bool,
    compute_intensive: bool = False,
    competitor_cores: Optional[int] = None,
) -> Tuple[str, List[str]]:
    """
    v2.5.0 Generate "node spec selection rationale" by computation formula logic chain (multi-step formulaic):

      ① Compute derivation (data volume → target vCPU): data volume ÷100GB/core (or migration parity), show original formula and rounding;
      ② Memory ratio (computing logic): query profile → 1:4 / 1:8, explain workload basis;
      ③ Concurrency/HA: production lower bound (per node ≥16 cores/64GB, nodes ≥3) → enumerate feasible combos per tier and total cores;
      ④ Storage/cache verification: hot data ÷ high watermark (±index) → per-node requirement → 100GB rounding (incl. storage medium context);
      ④ Conclusion directly after storage/cache verification;
      Conclusion line: final spec × node count = total vCPU/total memory/per-node storage.

    All numbers come from actual calculation results (plan/considered/storage), not static copy.

    Returns:
        (multi-line rationale text, step list select_reason_steps)
    """
    steps: List[str] = []

    # ① Compute derivation (data volume / migration parity → target vCPU)
    if scenario_type == "migration":
        if competitor_cores:
            steps.append(
                f"① Compute derivation (migration parity): competitor {competitor_cores} cores → target total vCPU={target_vcpu} cores"
            )
        else:
            steps.append(
                f"① Compute derivation (data volume fallback): {data_total_gb:,.0f}GB÷100GB/core={data_total_gb/100:.1f} → target total vCPU={target_vcpu} cores"
            )
    elif compute_intensive:
        base = ceil(data_total_gb / 100)
        steps.append(
            f"① Compute derivation (compute-intensive): base={data_total_gb:,.0f}GB÷100={base} cores, ×1.3 → target total vCPU={target_vcpu} cores"
        )
    else:
        steps.append(
            f"① Compute derivation (data volume): {data_total_gb:,.0f}GB÷100GB/core={data_total_gb/100:.1f} → rounded up target total vCPU={target_vcpu} cores"
        )

    # ② Memory ratio (computing logic / query profile)
    workload = "point query/high concurrency" if high_point_query else "report/batch analysis oriented"
    mem_note = "point query/secondary index heavy, need ample working memory" if high_point_query else "scan-aggregate workload, 1:4 balanced tier sufficient"
    steps.append(f"② Memory ratio (computing logic): {workload} → CPU:memory={ratio} ({mem_note}), filter candidates by {ratio} catalog")

    # ③ Concurrency + HA → feasible combos per tier (total cores ≥ target, nodes ≥3)
    combo_txt = ", ".join(
        f"{c['vcpu']} cores×{c['nodes']}={c['total_vcpu']} cores" for c in considered[:4]
    )
    steps.append(
        f"③ Concurrency/HA: per node ≥16 cores/64GB, nodes ≥3 → feasible combos {combo_txt}…"
    )

    # ④ Storage/cache capacity verification (formula: hot data ÷ high watermark (±index) → per-node rounding)
    hw = storage["high_water_level"]
    idx_txt = f"×(1+{storage['index_pct']:.0%})" if storage["index_pct"] > 0 else "(no index bonus)"
    steps.append(
        f"④ Storage verification ({storage['arch']}): hot data {storage['hot_data_gb']:,.0f}GB÷{hw:.0%} high watermark="
        f"{storage['effective_gb']:,.0f}GB{idx_txt}→total requirement {storage['total_require_gb']:,.0f}GB"
        f"÷{plan['node_count']} nodes={storage['per_node_require_gb']:,.0f}GB → "
        f"per node {plan['storage_per_node_gb']}GB (100GB rounding)"
    )

    # Conclusion line
    steps.append(
        f"→ Selected: {plan['flavor']}×{plan['node_count']} = {plan['total_vcpu']}vCPU/"
        f"{plan['total_memory_gb']}GB, per-node storage/cache {plan['storage_per_node_gb']}GB×{plan['node_count']}"
    )
    return "\n".join(steps), steps


def select_min_cost_plan(
    target_vcpu: int,
    ratio: str,
    architecture: str = "integrated",
    data_total_gb: float = 0.0,
    cache_policy: str = "performance",
    high_point_query: bool = True,
    index_pct: float = 0.30,
    hot_data_days: Optional[int] = None,          # v2.3.0 hot window days (compute-storage separation)
    daily_increment_gb: Optional[float] = None,   # v2.3.0 paired with hot window
    hot_data_gb_override: Optional[float] = None, # v2.3.0 custom hot data total GB (mixed data source hot profile)
) -> Dict[str, Any]:
    """
    Select "minimal spec meeting requirements": iterate spec catalog, satisfying these hard constraints:
      - Per-node vCPU >= 16 and memory >= 64GB (production lower bound)
      - Node count >= 3 (high availability)
      - Node count × per-node vCPU >= target total vCPU
    Among all feasible combos, take "minimum compute surplus + minimum node count" (highest resource utilization, simplest ops).
    Returns:
        plan dict (incl. spec, nodes, storage, candidate comparison considered)
    """
    arch_catalog = FLAVOR_CATALOG.get(architecture, FLAVOR_CATALOG["integrated"])
    catalog = arch_catalog.get(ratio, arch_catalog["1:4"])
    # Hard constraints: per node >= 16vCPU and >= 64GB
    prod_list = [f for f in catalog if f[1] >= MIN_NODE_VCPU and f[2] >= MIN_NODE_MEM_GB]
    if not prod_list:
        prod_list = catalog  # fallback

    candidates = []
    for flavor, vcpu, mem in prod_list:
        nodes = max(MIN_HA_NODES, ceil(target_vcpu / vcpu))
        total_vcpu = nodes * vcpu
        surplus = total_vcpu - target_vcpu
        storage = calc_storage(
            architecture, data_total_gb, nodes, cache_policy, high_point_query, index_pct,
            hot_data_days=hot_data_days, daily_increment_gb=daily_increment_gb,
            hot_data_gb_override=hot_data_gb_override,
        )
        per_node_final = storage["per_node_final_gb"]
        candidates.append({
            "flavor": flavor, "vcpu": vcpu, "memory_gb": mem,
            "nodes": nodes,
            "total_vcpu": total_vcpu, "total_memory_gb": mem * nodes,
            "surplus_vcpu": surplus,
            "per_node_final_gb": per_node_final,
        })

    # Sort key: compute surplus → node count (highest resource utilization + simplest ops)
    candidates.sort(key=lambda c: (c["surplus_vcpu"], c["nodes"]))
    best = candidates[0]

    nodes = best["nodes"]
    fault = f"-{round(100 / nodes)}% vCPU"
    plan = {
        "name": "Recommended plan (minimal spec meeting requirements)",
        "flavor": best["flavor"],
        "vcpu": best["vcpu"],
        "memory_gb": best["memory_gb"],
        "node_count": nodes,
        "total_vcpu": best["total_vcpu"],
        "total_memory_gb": best["total_memory_gb"],
        "fault_impact": fault,
        "considered": candidates,     # candidate comparison (for Sheet 3 decision rationale)
        "select_reason": (
            f"Iterate spec catalog, among combos satisfying total vCPU≥{target_vcpu} cores, per node ≥16 cores/64GB, ≥{MIN_HA_NODES} nodes HA, "
            f"{best['flavor']}×{nodes} nodes has minimum compute surplus ({best['surplus_vcpu']} cores, node count {nodes})"
        ),
    }
    return plan


