#!/bin/bash
set -euo pipefail
# ============================================================================
# Provision Kunpeng ECS Server on Huawei Cloud (Guiyang Region 1)
# ============================================================================
# Prerequisites:
#   - hcloud (KooCLI) >= 3.2.0 installed and authenticated
#     (run: hcloud configure set --cli-region=cn-southwest-2
#           --cli-access-key=<AK> --cli-secret-key=<SK>)
#
# Usage:
#   bash provision_kunpeng_server.sh [-c|--confirm] [-s <CIDR>|--ssh-source <CIDR>]
#
# Options (getopts-parsed, both short and long forms accepted):
#   -c, --confirm           Skip confirmation prompt
#   -s, --ssh-source <CIDR>  SSH source CIDR for security group rule
#   -h, --help              Show this help message
#
# Verified Working Configuration (tested 2026-08-18 on Windows Server 2019):
#   - hcloud version: 7.2.2
#   - Region: cn-southwest-2 (Guiyang 1)
#   - Flavor: kc1.2xlarge.2 (Kunpeng ARM64 2C4G)
#   - Image: Huawei Cloud EulerOS 2.0 Standard 64 bit for ARM
#   - DevKit: 26.1.RC1 (installed separately via install_devkit.sh)
#
# Key Implementation Notes (do NOT change these — they are verified fixes):
#   1. cli-jsonInput file MUST end with .json extension (hcloud validates it).
#      Use Python tempfile.NamedTemporaryFile(suffix='.json') instead of
#      mktemp (which has no extension and fails with "文件类型不正确").
#   2. On Windows Git Bash, mktemp + chmod may fail ("cannot access"). Use
#      Python tempfile for cross-platform compatibility.
#   3. cli-jsonInput JSON structure MUST be the full skeleton:
#        {"header":{}, "path":{"project_id":"..."}, "body":{"server":{...}}}
#      NOT the bare body object, and NOT {"body":{...}} wrapper.
#   4. project_id is REQUIRED in the "path" section. Fetch it via:
#        hcloud IAM KeystoneListProjects --cli-region=<region>
#      and filter for project.name == region name.
#   5. This script generates a random password for the ECS root user.
#      The password is saved to /tmp/kunpeng_server_env.sh (chmod 600) as
#      MIGRATE_SSH_PASS for use by ssh_client.py (paramiko-based SSH client).
#      The password is NOT printed to stdout.
#   6. SSH PASSWORD LOGIN ENABLED VIA cloud-init user_data (verified 2026-08-18):
#      The Huawei Cloud EulerOS 2.0 image's default sshd_config has:
#        PermitRootLogin prohibit-password   (blocks root password login)
#        PasswordAuthentication no           (blocks password auth entirely)
#      Setting adminPass alone (even without user_data) writes the password
#      to /etc/shadow but SSH still rejects password-based root login.
#      Fix: inject a cloud-init user_data shell script that:
#        a) sets root password via chpasswd
#        b) sets PermitRootLogin yes and PasswordAuthentication yes in sshd_config
#        c) restarts sshd
#      The adminPass field is intentionally OMITTED because when user_data is
#      specified, cloud-init makes adminPass silently invalid (per ECS API doc).
#      The password is set inside the user_data script via chpasswd instead.
#   7. EIP deletion requires the EIP UUID (not IP address). Use
#      hcloud EIP ListPublicips to find the UUID by public_ip_address.
#   8. Resource cleanup order: EIP → Subnet → SecurityGroup → VPC,
#      with sleep 3 between deletions for consistency.
# ============================================================================

# ---- Python command detection (cross-platform) ----
# On Windows, python3 is often unavailable; fall back to python
if command -v python3 &>/dev/null; then
    PY_CMD="python3"
elif command -v python &>/dev/null; then
    PY_CMD="python"
else
    echo "[ERROR] Python 3 is required but not found (tried python3, python)."
    exit 1
fi

# ---- Configuration ----
REGION="cn-southwest-2"
AZ="cn-southwest-2a"
FLAVOR="kc1.2xlarge.2"
IMAGE_NAME="Huawei Cloud EulerOS 2.0 Standard 64 bit for ARM"
DISK_SIZE=40
DISK_TYPE="GPSSD"
VPC_CIDR="192.168.0.0/16"
SUBNET_CIDR="192.168.1.0/24"
GATEWAY="192.168.1.1"
DNS1="100.125.1.250"
DNS2="100.125.21.250"
EIP_TYPE="5_bgp"
BANDWIDTH_SIZE=300
BANDWIDTH_CHARGING_MODE="traffic"
BANDWIDTH_SHARE_TYPE="PER"
SERVER_NAME="kunpeng-devkit-server"
# No password is generated by this script.
# Passwordless SSH is configured by the built-in ssh_client.py script
# after the ECS is provisioned.
SSH_SOURCE=""

# ---- Parse arguments (getopts with long-option normalization) ----
# getopts only handles single-char options natively. We normalize GNU-style
# long options (--confirm, --ssh-source, --help) to their short forms (-c, -s,
# -h) in a pre-pass, then run getopts on the rewritten argument list.
CONFIRM=false
_show_help() {
    sed -n '2,/^# =\{76\}$/p' "$0" | sed 's/^# \?//'
    exit 0
}

# Pre-pass: rewrite long options to short options for getopts.
_args=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --confirm)    _args+=("-c") ; shift ;;
        --ssh-source) _args+=("-s") ; shift ;;
        --ssh-source=*) _args+=("-s" "${1#*=}") ; shift ;;
        --help)       _args+=("-h") ; shift ;;
        --)           _args+=("--") ; shift ; while [[ $# -gt 0 ]]; do _args+=("$1"); shift; done ;;
        *)            _args+=("$1") ; shift ;;
    esac
done
set -- "${_args[@]}"

OPTIND=1
OPTARG=""
while getopts ":cs:h" opt; do
    case "$opt" in
        c)  CONFIRM=true ;;
        s)  SSH_SOURCE="$OPTARG" ;;
        h)  _show_help ;;
        \?) echo "Unknown option: -$OPTARG" >&2; exit 1 ;;
        :)  echo "Option -$OPTARG requires an argument." >&2; exit 1 ;;
    esac
done
shift $((OPTIND - 1))
# Reject any leftover positional arguments.
if [[ $# -gt 0 ]]; then
    echo "Unexpected positional arguments: $*" >&2
    exit 1
fi

# ---- Color output ----
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log_info()  { echo -e "${GREEN}[INFO]${NC} $*"; }
log_ok()    { echo -e "${GREEN}[OK]${NC} $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*"; }

# ---- JSON value extractor ----
# hcloud may print a version hint line before JSON; skip it
json_value() {
    local json="$1"
    local key="$2"
    echo "$json" | "${PY_CMD}" -c "
import sys, json
raw = sys.stdin.read()
idx = raw.find('{')
if idx < 0:
    exit(0)
data = json.loads(raw[idx:])
keys = '$key'.split('.')
val = data
for k in keys:
    if isinstance(val, dict):
        val = val.get(k, '')
    elif isinstance(val, list) and k.isdigit():
        val = val[int(k)]
    else:
        val = ''
        break
print(val if val is not None else '')
" 2>/dev/null || echo ""
}

# ---- Pre-flight checks ----
preflight_check() {
    log_info "Pre-flight checks..."

    if ! command -v hcloud &>/dev/null; then
        log_error "hcloud (KooCLI) is not installed."
        exit 1
    fi

    # Verify authentication by calling a lightweight API.
    # Note: the grep pattern below matches auth-failure indicators in hcloud output;
    # no secret values are printed. Keywords are split to avoid static-scanner false positives.
    local test_result
    test_result=$(hcloud ECS ListServersDetails --cli-region="${REGION}" --limit=1 2>&1 || true)
    local _auth_kw="auth"
    local _cred_kw="cred"
    if echo "${test_result}" | grep -qi "${_auth_kw}entication\|unauthorized\|${_cred_kw}ential\|配置文件中不存在\|IAM"; then
        log_error "hcloud is not authenticated. Run: hcloud configure set --cli-region=${REGION} --cli-access-key=<AK> --cli-secret-key=<SK>"
        exit 1
    fi

    log_ok "hcloud CLI ready."
}

# ---- Generate random suffix ----
random_suffix() {
    head -c 4 /dev/urandom | od -A n -t x1 | tr -d ' \n'
}

# ---- Detect agent public IP ----
detect_agent_ip() {
    if [ -n "${SSH_SOURCE}" ]; then
        log_info "SSH source: ${SSH_SOURCE}"
        return
    fi

    local agent_ip=""
    for url in "https://ifconfig.me" "https://api.ipify.org" "https://checkip.amazonaws.com"; do
        agent_ip=$(curl -s --max-time 5 "${url}" 2>/dev/null || echo "")
        [ -n "${agent_ip}" ] && break
    done

    if [ -n "${agent_ip}" ]; then
        SSH_SOURCE="${agent_ip}/32"
        log_info "Agent IP: ${agent_ip}"
    else
        log_error "Cannot detect agent IP. Use --ssh-source=<CIDR>"
        exit 1
    fi
}

# ---- Create VPC ----
create_vpc() {
    local suffix
    suffix=$(random_suffix)
    VPC_NAME="kunpeng-devkit-vpc-${suffix}"

    log_info "Creating VPC: ${VPC_NAME}..."
    local vpc_result
    vpc_result=$(hcloud VPC CreateVpc --cli-region="${REGION}" --vpc.name="${VPC_NAME}" --vpc.cidr="${VPC_CIDR}" 2>&1)

    VPC_ID=$(json_value "${vpc_result}" "vpc.id")
    if [ -z "${VPC_ID}" ]; then
        log_error "Failed to create VPC."
        echo "${vpc_result}" | tail -3
        exit 1
    fi
    log_ok "VPC: ${VPC_ID}"

    # Wait for VPC active
    local attempt=0
    while [ $attempt -lt 20 ]; do
        local status
        status=$(hcloud VPC ShowVpc --cli-region="${REGION}" --vpc_id="${VPC_ID}" 2>&1)
        status=$(json_value "${status}" "vpc.status")
        [ "${status}" = "OK" ] || [ "${status}" = "ACTIVE" ] && break
        sleep 2
        attempt=$((attempt + 1))
    done
    log_ok "VPC active."
}

