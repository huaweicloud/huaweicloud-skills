}

# ---- Create ECS Instance ----
# NOTE: We use --cli-jsonInput with a temporary file instead of command-line
# arguments to avoid leaking server.adminPass via the process list (ps -ef).
# The password is passed to Python via stdin (not argv) so it never appears
# in the process list. Only non-sensitive parameters use argv.
#
# The generated password is saved to /tmp/kunpeng_server_env.sh as
# MIGRATE_SSH_PASS for use by ssh_client.py (paramiko-based SSH client).
# It is NOT printed to stdout.
create_ecs() {
    log_info "Creating ECS: ${SERVER_NAME}..."

    # Generate a random password for the ECS root user.
    # This password is saved to the env file for ssh_client.py to use.
    #
    # IMPORTANT: The special character set MUST satisfy BOTH:
    #   - Huawei Cloud ResetServerPassword API: !@%-_=+[]:./?
    #   - Linux chpasswd: no shell-unsafe chars (backslash, quotes, backtick,
    #     dollar, semicolon, pipe, ampersand, space)
    # We use the intersection: !@%-_=+[]:./?  (ResetServerPassword set,
    # which is the stricter one and also chpasswd-safe).
    #
    # RATIONALE: We set the password via cloud-init user_data (chpasswd),
    # NOT via the adminPass field. See the user_data section below for why.
    local server_password
    server_password="$("${PY_CMD}" -c '
import secrets, string
upper = string.ascii_uppercase
lower = string.ascii_lowercase
digit = string.digits
# Use the ResetServerPassword allowed set (stricter than CreateServers
# adminPass set) to keep the password compatible with both APIs and
# safe for shell scripts / env files / chpasswd.
special = "!@%-_=+[]:./?"
parts = [
    secrets.choice(upper),
    secrets.choice(lower),
    secrets.choice(digit),
    secrets.choice(special),
]
all_chars = upper + lower + digit + special
parts += [secrets.choice(all_chars) for _ in range(16)]
secrets.SystemRandom().shuffle(parts)
print("".join(parts))
')"

    # Build the cloud-init user_data script.
    #
    # WHY user_data INSTEAD OF adminPass:
    #   The Huawei Cloud EulerOS 2.0 image has cloud-init installed. According
    #   to the ECS CreateServers API doc, when user_data is specified, adminPass
    #   is silently ignored. So we do NOT rely on adminPass.
    #
    #   Instead, we inject a shell script via user_data that:
    #     1. Sets the root password via chpasswd
    #     2. Enables PermitRootLogin yes in sshd_config
    #     3. Enables PasswordAuthentication yes in sshd_config
    #     4. Restarts sshd
    #
    #   This is necessary because EulerOS 2.0's default sshd_config has:
    #     PermitRootLogin prohibit-password   (blocks root password login)
    #     PasswordAuthentication no           (blocks password auth entirely)
    #   Even if adminPass correctly sets /etc/shadow, SSH still rejects
    #   password-based root login. The user_data script fixes sshd_config.
    #
    #   The password is passed to the Python script via stdin (not argv) so
    #   it never appears in the process list (ps -ef).
    local json_input
    json_input=$("${PY_CMD}" -c "import tempfile, os; f = tempfile.NamedTemporaryFile(mode='w', suffix='.json', delete=False); f.close(); print(f.name)")

    local project_id
    project_id=$(hcloud IAM KeystoneListProjects --cli-region="${REGION}" 2>&1 | "${PY_CMD}" -c "
import sys, json
raw = sys.stdin.read()
idx = raw.find('{')
data = json.loads(raw[idx:])
for p in data.get('projects', []):
    if p.get('name', '') == '${REGION}':
        print(p.get('id', ''))
        break
")
    if [ -z "${project_id}" ]; then
        log_error "Failed to get project_id for region ${REGION}."
        exit 1
    fi
    log_info "Project ID: ${project_id}"

    printf '%s' "${server_password}" | "${PY_CMD}" -c "
import json, sys, base64
admin_pass = sys.stdin.read()
# Build the cloud-init user_data shell script.
# This script runs as root during first boot via cloud-init.
# We use a placeholder __ROOT_PASS__ for the password and substitute it
# after, to avoid any Python string-literal parsing issues with the
# password's special characters.
cloud_init_script = '''#!/bin/bash
# Set root password via chpasswd
echo 'root:__ROOT_PASS__' | chpasswd
# Enable root password login in sshd_config
sed -i 's/^#*PermitRootLogin.*/PermitRootLogin yes/' /etc/ssh/sshd_config
sed -i 's/^#*PasswordAuthentication.*/PasswordAuthentication yes/' /etc/ssh/sshd_config
# Ensure the directives exist (append if sed did not match any line)
grep -q '^PermitRootLogin yes' /etc/ssh/sshd_config || echo 'PermitRootLogin yes' >> /etc/ssh/sshd_config
grep -q '^PasswordAuthentication yes' /etc/ssh/sshd_config || echo 'PasswordAuthentication yes' >> /etc/ssh/sshd_config
# Restart sshd (try multiple init systems for portability)
systemctl restart sshd 2>/dev/null || service sshd restart 2>/dev/null || /etc/init.d/sshd restart 2>/dev/null
'''
# Substitute the placeholder with the actual password.
# The password only contains: A-Z a-z 0-9 !@%-_=+[]:./?
# None of these chars are special in shell single-quoted strings,
# so wrapping the chpasswd input in single quotes (already in the script)
# keeps the password safe from shell expansion.
cloud_init_script = cloud_init_script.replace('__ROOT_PASS__', admin_pass)
user_data_b64 = base64.b64encode(cloud_init_script.encode('utf-8')).decode('ascii')
body = {
    'header': {},
    'path': {'project_id': sys.argv[11]},
    'body': {
        'server': {
            'name': sys.argv[1],
            'imageRef': sys.argv[2],
            'flavorRef': sys.argv[3],
            'vpcid': sys.argv[4],
            'nics': [{'subnet_id': sys.argv[5]}],
            'publicip': {'id': sys.argv[6]},
            'root_volume': {'volumetype': sys.argv[7], 'size': int(sys.argv[8])},
            'security_groups': [{'id': sys.argv[9]}],
            'availability_zone': sys.argv[10],
            'user_data': user_data_b64,
        }
    }
}
print(json.dumps(body))
" "${SERVER_NAME}" "${IMAGE_ID}" "${FLAVOR}" "${VPC_ID}" "${SUBNET_ID}" \
        "${EIP_ID}" "${DISK_TYPE}" "${DISK_SIZE}" "${SECGROUP_ID}" "${AZ}" \
        "${project_id}" \
        > "${json_input}"

    local ecs_result
    ecs_result=$(hcloud ECS CreateServers --cli-region="${REGION}" \
        --cli-jsonInput="${json_input}" 2>&1)
    local rc=$?

    shred -u "${json_input}" 2>/dev/null || rm -f "${json_input}"

    if [ $rc -ne 0 ]; then
        log_error "Failed to create ECS."
        echo "${ecs_result}" | tail -5
        server_password=""
        exit 1
    fi

    JOB_ID=$(json_value "${ecs_result}" "job_id")
    SERVER_ID=$(json_value "${ecs_result}" "serverIds.0")

    if [ -z "${JOB_ID}" ]; then
        log_error "Failed to create ECS."
        echo "${ecs_result}" | tail -5
        server_password=""
        exit 1
    fi
    log_ok "ECS job: ${JOB_ID}"

    # Save the password to a secure temp variable for save_connection_info.
    # The password is written to the env file (chmod 600) later.
    echo "${server_password}" > "${TMP_DIR:-/tmp}/.migrate_ecs_pass"
    chmod 600 "${TMP_DIR:-/tmp}/.migrate_ecs_pass" 2>/dev/null || true
    server_password=""
}

# ---- Wait for ECS ready ----
wait_for_ecs() {
    log_info "Waiting for ECS (may take 2-3 minutes)..."
    local attempt=0
    while [ $attempt -lt 60 ]; do
        local job_result
        job_result=$(hcloud ECS ShowJob --cli-region="${REGION}" --job_id="${JOB_ID}" 2>&1)
        local job_status
        job_status=$(json_value "${job_result}" "status")

        if [ "${job_status}" = "SUCCESS" ]; then
            if [ -z "${SERVER_ID}" ]; then
                SERVER_ID=$(json_value "${job_result}" "entities.sub_jobs.0.entities.server_id")
            fi
            log_ok "ECS created. Server ID: ${SERVER_ID}"
            return 0
        elif [ "${job_status}" = "FAIL" ]; then
            log_error "ECS creation failed."
            exit 1
        fi

        sleep 5
        attempt=$((attempt + 1))
    done
    log_error "ECS creation timed out."
    exit 1
}

# ---- Save connection info ----
# This function saves the ECS connection info AND the generated password
# (as MIGRATE_SSH_PASS) to /tmp/kunpeng_server_env.sh (chmod 600).
# The password is used by ssh_client.py for paramiko-based SSH connection.
save_connection_info() {
    local env_file="/tmp/kunpeng_server_env.sh"
    local pass_file="${TMP_DIR:-/tmp}/.migrate_ecs_pass"

    # Save connection info AND the password (for ssh_client.py paramiko mode).
    # The env file is chmod 600 — only readable by the current user.
    # The password is read from the temp file created by create_ecs.
    local saved_password=""
    if [ -f "${pass_file}" ]; then
        saved_password=$(cat "${pass_file}")
        shred -u "${pass_file}" 2>/dev/null || rm -f "${pass_file}"
    else
        log_warn "Password temp file not found: ${pass_file}"
        log_warn "MIGRATE_SSH_PASS will NOT be written to env file."
        log_warn "You will need to reset the password manually via:"
        log_warn "  hcloud ECS ResetServerPassword --cli-region=${REGION} --server_id=${SERVER_ID} --reset-password.new_password=<new_pass>"
    fi

    {
        echo "# Kunpeng ECS connection info (SSH via paramiko + secret env var)"
        echo "export KUNPENG_SERVER_HOST=\"${EIP_ADDRESS}\""
        echo "export KUNPENG_SERVER_PORT=\"22\""
        echo "export KUNPENG_SERVER_USER=\"root\""
        echo "export KUNPENG_SERVER_ID=\"${SERVER_ID}\""
        echo "export KUNPENG_SERVER_REGION=\"${REGION}\""
        if [ -n "${saved_password}" ]; then
            echo "export MIGRATE_SSH_PASS=\"${saved_password}\""
        fi
    } > "${env_file}"
    chmod 600 "${env_file}"

    # Clear password from memory
    saved_password=""

    echo ""
    log_ok "============================================"
    log_ok "  Kunpeng ECS Server Provisioned!"
    log_ok "============================================"
    echo "  Instance ID:  ${SERVER_ID}"
    echo "  IP:           ${EIP_ADDRESS}"
    echo "  Region:       ${REGION}"
    echo "  User:         root"
    echo "  Flavor:       ${FLAVOR} (ARM64 2C4G)"
    echo "  Image:        ${IMAGE_NAME}"
    echo "  Disk:         ${DISK_SIZE}GB ${DISK_TYPE}"
    echo ""
    log_info "Env file: ${env_file} (chmod 600, contains MIGRATE_SSH_PASS)"
    log_info "Load with: source ${env_file}"
    echo ""
    log_info "NEXT STEP: Verify SSH by running the built-in script:"
    log_info "  python <skill_dir>/scripts/ssh_client.py test"
    log_info "  (reads MIGRATE_SSH_PASS from env, verifies paramiko password connection)"
    log_info "  All subsequent SSH operations use ssh_client.py:"
    log_info "    python <skill_dir>/scripts/ssh_client.py exec \"<command>\" [timeout]"
    echo ""
    log_warn "This server incurs charges. After the assessment completes, the AI will remind you to:"
    log_warn "  Delete the server and related resources manually"
    echo ""
    echo "  ⚠️  Resource deletion is IRREVERSIBLE. AI will NOT auto-execute delete commands."
