    if [ -z "${IMAGE_ID}" ]; then
        # Method 2: Try with platform filter
        images_result=$(hcloud IMS ListImages --cli-region="${REGION}" \
            --__imagetype=gold \
            "--__platform=Huawei Cloud EulerOS" \
            --limit=50 2>&1)

        IMAGE_ID=$(echo "${images_result}" | "${PY_CMD}" -c "
import sys, re
content = sys.stdin.read()
id_pattern = re.compile(r'\"id\":\s*\"([a-f0-9-]+)\"')
name_pattern = re.compile(r'\"name\":\s*\"([^\"]+)\"')
ids = id_pattern.findall(content)
names = name_pattern.findall(content)
