# ---- Create Security Group + SSH rule ----
create_security_group() {
    local suffix
    suffix=$(random_suffix)
    SECGROUP_NAME="kunpeng-devkit-sg-${suffix}"

    log_info "Creating Security Group: ${SECGROUP_NAME}..."
    local sg_result
    sg_result=$(hcloud VPC CreateSecurityGroup --cli-region="${REGION}" --security_group.name="${SECGROUP_NAME}" 2>&1)

    SECGROUP_ID=$(json_value "${sg_result}" "security_group.id")
    if [ -z "${SECGROUP_ID}" ]; then
        log_error "Failed to create Security Group."
        echo "${sg_result}" | tail -3
        exit 1
    fi
    log_ok "Security Group: ${SECGROUP_ID}"

    # Add SSH inbound rule (try v3 API first, then v2)
    log_info "Adding SSH rule (TCP 22 from ${SSH_SOURCE})..."
    local rule_result
    rule_result=$(hcloud VPC CreateSecurityGroupRule --cli-region="${REGION}" \
        --security_group_rule.security_group_id="${SECGROUP_ID}" \
        --security_group_rule.direction="ingress" \
        --security_group_rule.protocol="tcp" \
        --security_group_rule.multiport="22" \
        --security_group_rule.remote_ip_prefix="${SSH_SOURCE}" \
        --security_group_rule.ethertype="IPv4" \
        --security_group_rule.action="allow" \
        --security_group_rule.priority="1" 2>&1 || true)

    if echo "${rule_result}" | grep -qi "error\|USE_ERROR\|0403"; then
        log_warn "SSH rule needs to be added manually in console:"
        log_warn "  SG: ${SECGROUP_NAME}, Ingress: TCP 22, Source: ${SSH_SOURCE}"
        SECGROUP_RULE_MANUAL=true
    else
        log_ok "SSH rule added."
        SECGROUP_RULE_MANUAL=false
    fi
}

# ---- Get Image ID ----
get_image_id() {
    log_info "Finding image: ${IMAGE_NAME}..."

    # Method 1: Search via IMS ListImages with platform filter
    # The correct platform value is "Huawei Cloud EulerOS" (with spaces)
    local images_result
    images_result=$(hcloud IMS ListImages --cli-region="${REGION}" \
        --__imagetype=gold \
        --__os_type=Linux \
        --limit=50 2>&1)

    # Extract image ID for "Huawei Cloud EulerOS 2.0 Standard 64 bit for ARM"
    # excluding BareMetal images
    IMAGE_ID=$(echo "${images_result}" | "${PY_CMD}" -c "
import sys, re
content = sys.stdin.read()
# Split by image blocks using 'id' as anchor
id_pattern = re.compile(r'\"id\":\s*\"([a-f0-9-]+)\"')
name_pattern = re.compile(r'\"name\":\s*\"([^\"]+)\"')
ids = id_pattern.findall(content)
names = name_pattern.findall(content)
for img_id, img_name in zip(ids, names):
    if 'Standard 64 bit for ARM' in img_name and 'BareMetal' not in img_name and 'EulerOS' in img_name:
        print(img_id)
        break
